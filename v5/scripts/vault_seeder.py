def main():
    dry = "--dry-run" in sys.argv
    print(f"=== Vault Seeder ({'DRY' if dry else 'WRITE'}) ===")

    total_new = 0
    total_skip = 0
    total_all = 0

    def _write(path, content):
        nonlocal total_new, total_skip, total_all
        total_all += 1
        if path.exists() and "--force" not in sys.argv:
            total_skip += 1
            return False
        if not dry:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            total_new += 1
        return True

    print("  标的:", len(STOCKS))
    for code, name, industry in STOCKS:
        _write(VAULT / "01-标的" / f"{code}-{name}.md", stock_note(code, name, industry))

    print("  框架:", len(FRAMES))
    for fn, title, desc in FRAMES:
        _write(VAULT / "02-框架" / fn, frame_note(title, desc))

    print("  数据:", len(DATA_DOCS))
    for fn, title, desc in DATA_DOCS:
        _write(VAULT / "03-数据" / fn, data_note(title, desc))

    print("  回测:", len(BACKTESTS))
    for fn, title, desc in BACKTESTS:
        _write(VAULT / "04-回测" / fn, backtest_note(title, desc))

    print("  知识:", len(KNOWLEDGE))
    for fn, title, desc in KNOWLEDGE:
        _write(VAULT / "05-知识库" / fn, knowledge_note(title, desc))

    print("  模板:", len(TEMPLATES))
    for fn, title, desc in TEMPLATES:
        _write(VAULT / "06-模板" / fn, template_note(title, desc))

    print("  日记: 1")
    _write(VAULT / "07-日记" / f"{TODAY}.md", daily_note())

    print()
    print(f"  合计: {total_all} 个 ({total_new} 新建 / {total_skip} 已存在跳过)")
    if dry:
        print("  DRY-RUN，未实际创建")


if __name__ == "__main__":
    main()
